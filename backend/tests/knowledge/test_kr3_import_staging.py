class TestCandidateNonProduction:
    def test_staged_candidates_not_in_production_eligible(
        self, repo: ManagedKRRepository, valid_payload: ImportPayload
    ) -> None:
        staging = stage_import_payload(valid_payload, repo)
        staged_ids = set(staging.record_ids)
        production = repo.list_production_eligible()
        production_ids = {r.record_id for r in production}
        assert staged_ids.isdisjoint(production_ids), (
            f"Staged candidate IDs appeared in production-eligible list: "
            f"{staged_ids & production_ids}"
        )

    def test_staged_candidates_not_in_list_approved(
        self, repo: ManagedKRRepository, valid_payload: ImportPayload
    ) -> None:
        staging = stage_import_payload(valid_payload, repo)
        staged_ids = set(staging.record_ids)
        approved = repo.list_approved()
        approved_ids = {r.record_id for r in approved}
        assert staged_ids.isdisjoint(approved_ids)

    def test_staged_candidates_not_in_list_seeds(
        self, repo: ManagedKRRepository, valid_payload: ImportPayload
    ) -> None:
        stage_import_payload(valid_payload, repo)
        seeds = repo.list_seeds()
        seed_ids = {r.record_id for r in seeds}
        assert not any(rid.startswith("import_") for rid in seed_ids)

    def test_staged_curve_def_status_is_candidate(
        self, repo: ManagedKRRepository, valid_payload: ImportPayload
    ) -> None:
        staging = stage_import_payload(valid_payload, repo)
        for rid in staging.record_ids:
            record = repo.get_by_id(rid)
            assert record is not None
            assert record.status == GovernanceStatus.CANDIDATE, (
                f"Record {rid} has status {record.status}, expected CANDIDATE"
            )


