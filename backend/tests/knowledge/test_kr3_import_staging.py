class TestEvidenceRefs:
    def test_staged_curve_def_has_evidence_refs(
        self, repo: ManagedKRRepository, valid_payload: ImportPayload
    ) -> None:
        staging = stage_import_payload(valid_payload, repo)
        expected_ev_id = f"import_evidence_{staging.import_batch_id}"
        for rid in staging.record_ids:
            record = repo.get_by_id(rid)
            assert record is not None
            refs = getattr(record, "evidence_refs", [])
            assert expected_ev_id in refs, (
                f"Record {rid} missing evidence_ref '{expected_ev_id}': {refs}"
            )

    def test_staged_alias_has_evidence_refs(
        self, repo: ManagedKRRepository, valid_payload: ImportPayload
    ) -> None:
        staging = stage_import_payload(valid_payload, repo)
        expected_ev_id = f"import_evidence_{staging.import_batch_id}"
        aliases = [
            r for r in repo.list_candidates()
            if r.record_type == "alias" and r.record_id.startswith("import_")
        ]
        assert aliases, "No staged alias candidates found"
        for alias_rec in aliases:
            assert expected_ev_id in alias_rec.evidence_refs


